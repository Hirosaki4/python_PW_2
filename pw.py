

# Введення числа користувачем
number = int(input("Введіть трицифрове число: "))

# Отримання першої та останньої цифри
first_digit = number // 100      # Цілочисельне ділення — перша цифра
last_digit = number % 10         # Остача від ділення — остання цифра

# Перевірка, чи перша та остання цифри однакові
if first_digit == last_digit:
    print("Число є паліндромом")
else:
    print("Число не є паліндромом")
